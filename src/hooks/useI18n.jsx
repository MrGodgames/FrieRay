const I18nContext = createContext(null);

export function I18nProvider({ children }) {
    const [language, setLanguage] = useState(() => localStorage.getItem(LANGUAGE_KEY) || 'ru');

    useEffect(() => {
        const safeLanguage = dictionary[language] ? language : 'ru';
        document.documentElement.setAttribute('lang', safeLanguage);
        localStorage.setItem(LANGUAGE_KEY, safeLanguage);
    }, [language]);

    const value = useMemo(() => {
        const safeLanguage = dictionary[language] ? language : 'ru';
        const t = (key, params = {}) => {
            const entry = dictionary[safeLanguage][key] ?? dictionary.ru[key] ?? key;
            return typeof entry === 'function' ? entry(params) : entry;
        };
        return { language: safeLanguage, setLanguage, t, languages };
    }, [language]);

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
    const context = useContext(I18nContext);
    if (!context) {
        throw new Error('useI18n must be used within I18nProvider');
    }
    return context;
}
